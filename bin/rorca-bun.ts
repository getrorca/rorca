/**
 * DIST-004: Bun-compiled Rorca binary entry point.
 *
 * This is the single entry point for `bun build --compile`. It:
 *   1. Handles CLI (--version, --help, start, init)
 *   2. Sets up environment for the Express backend
 *   3. Writes embedded frontend assets to a temp directory
 *   4. Writes embedded SQL migrations to a temp directory
 *   5. Starts the Express server in-process (no fork/spawn)
 *
 * The bun:sqlite shim replaces better-sqlite3 at bundle time.
 */

declare const RORCA_VERSION: string;

import { existsSync, mkdirSync, writeFileSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { execSync } from 'child_process';
import { homedir, tmpdir } from 'os';

// ── Embedded assets (generated by build-binary.ts) ──
import { embeddedAssets, embeddedMigrations } from './.generated/embedded-assets';

// ── Version ──
const VERSION = typeof RORCA_VERSION !== 'undefined' ? RORCA_VERSION : '0.1.0';

// ── CLI ──
const args = process.argv.slice(2);

if (args.includes('--version') || args.includes('-v')) {
  console.log(VERSION);
  process.exit(0);
}

if (args.includes('--help') || args.includes('-h') || args.length === 0) {
  console.log(`
rorca v${VERSION} — AI spec orchestration pipeline (standalone binary)

Usage:
  rorca start [options]    Start the Rorca server
  rorca init               Register Rorca as an MCP server with claude CLI
  rorca --version          Print version
  rorca --help             Show this help message

Options for start:
  --port <port>            Server port (default: 3030)
  --no-open                Don't open browser on start

Examples:
  rorca start
  rorca start --port 4040
  rorca start --no-open
`);
  process.exit(0);
}

const command = args[0];

if (command === 'init') {
  runInit();
  process.exit(0);
}

if (command === 'start') {
  await runStart(args.slice(1));
} else {
  console.error(`Unknown command: ${command}\nRun "rorca --help" for usage.`);
  process.exit(1);
}

// ────────────────────────────────────────────────────────────────
// init: register MCP server with claude CLI
// ────────────────────────────────────────────────────────────────

function runInit(): void {
  console.log('Initializing Rorca MCP integration...\n');

  const claudeBin = findBinary('claude');
  if (!claudeBin) {
    console.log('Claude CLI not found in PATH.\n');
    console.log('To register Rorca as an MCP server manually, run:');
    console.log('  claude mcp add --global rorca --transport http http://localhost:3030/mcp\n');
    return;
  }

  console.log(`Found claude at: ${claudeBin}`);

  try {
    const listOutput = execSync(`${claudeBin} mcp list 2>&1`, { encoding: 'utf8' });
    if (listOutput.includes('rorca')) {
      console.log('Rorca is already registered as an MCP server.');
      return;
    }
  } catch {
    // mcp list may not exist — proceed
  }

  try {
    execSync(
      `${claudeBin} mcp add --global rorca --transport http http://localhost:3030/mcp`,
      { stdio: 'inherit' }
    );
    console.log('\nRorca MCP server registered successfully.');
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    if (msg.includes('already') || msg.includes('exists')) {
      console.log('Rorca MCP server is already registered.');
    } else {
      console.error('Failed to register MCP server:', msg);
    }
  }
}

// ────────────────────────────────────────────────────────────────
// start: extract embedded assets + launch Express in-process
// ────────────────────────────────────────────────────────────────

async function runStart(startArgs: string[]): Promise<void> {
  const portIdx = startArgs.indexOf('--port');
  const port = portIdx !== -1 && startArgs[portIdx + 1] ? startArgs[portIdx + 1] : '3030';
  const noOpen = startArgs.includes('--no-open');

  const portNum = parseInt(port, 10);
  if (isNaN(portNum) || portNum < 1 || portNum > 65535) {
    console.error(`Invalid port: ${port}`);
    process.exit(1);
  }

  // ── Ensure ~/.rorca/ config directory exists ──
  const rorcaHome = join(homedir(), '.rorca');
  if (!existsSync(rorcaHome)) {
    mkdirSync(rorcaHome, { recursive: true });
    console.log(`Created config directory: ${rorcaHome}`);
  }

  const dbPath = join(rorcaHome, 'rorca.db');

  // ── Clean up stale WAL files if DB doesn't exist (prevents SQLITE_IOERR_SHORT_READ) ──
  if (!existsSync(dbPath)) {
    const { unlinkSync } = await import('fs');
    for (const ext of ['-shm', '-wal']) {
      const walFile = dbPath + ext;
      if (existsSync(walFile)) {
        try { unlinkSync(walFile); } catch { /* best-effort */ }
      }
    }
  }

  // ── Extract embedded frontend assets to a temp directory ──
  const staticDir = join(rorcaHome, 'static');
  console.log('Extracting frontend assets...');
  extractEmbeddedAssets(staticDir);

  // ── Extract embedded SQL migrations ──
  const migrationsDir = join(rorcaHome, 'migrations');
  console.log('Extracting SQL migrations...');
  extractEmbeddedMigrations(migrationsDir);

  // ── Set environment for Express backend ──
  process.env.PORT = String(portNum);
  process.env.DB_PATH = dbPath;
  process.env.RORCA_SERVE_STATIC = '1';
  process.env.RORCA_STATIC_DIR = staticDir;
  process.env.RORCA_HOME = rorcaHome;
  process.env.RORCA_MIGRATIONS_DIR = migrationsDir;
  process.env.NODE_ENV = process.env.NODE_ENV || 'production';

  console.log(`Starting Rorca on port ${portNum}...`);
  console.log(`Database: ${dbPath}`);
  console.log(`Static files: ${staticDir}`);

  // ── Import and start the Express server in-process ──
  // The server.ts module auto-starts on import (calls app.listen)
  try {
    await import('../backend/src/server');
  } catch (err) {
    console.error('Failed to start server:', err);
    process.exit(1);
  }

  // Open browser after short delay
  if (!noOpen) {
    setTimeout(() => {
      openBrowser(`http://localhost:${portNum}`);
    }, 1500);
  }

  // Keep process alive — Express handles its own lifecycle
  // Forward signals for clean shutdown
  for (const sig of ['SIGINT', 'SIGTERM'] as const) {
    process.on(sig, () => {
      stopManagedPostgres();
      process.exit(0);
    });
  }
}

// ────────────────────────────────────────────────────────────────
// Asset extraction
// ────────────────────────────────────────────────────────────────

function extractEmbeddedAssets(targetDir: string): void {
  let extracted = 0;
  for (const [relPath, embeddedPath] of embeddedAssets) {
    const outPath = join(targetDir, relPath);
    const outDir = dirname(outPath);
    if (!existsSync(outDir)) {
      mkdirSync(outDir, { recursive: true });
    }
    // Read from bun's embedded filesystem and write to disk
    try {
      const content = readFileSync(embeddedPath);
      writeFileSync(outPath, content);
      extracted++;
    } catch (err) {
      // Fallback: try Bun.file() API
      try {
        const file = Bun.file(embeddedPath);
        const buf = Buffer.from(file.stream() as any);
        writeFileSync(outPath, buf);
        extracted++;
      } catch {
        console.warn(`  Warning: Could not extract ${relPath}`);
      }
    }
  }
  console.log(`  Extracted ${extracted}/${embeddedAssets.size} frontend files`);
}

function extractEmbeddedMigrations(targetDir: string): void {
  if (!existsSync(targetDir)) {
    mkdirSync(targetDir, { recursive: true });
  }
  for (const [filename, sql] of embeddedMigrations) {
    writeFileSync(join(targetDir, filename), sql);
  }
  console.log(`  Extracted ${embeddedMigrations.size} migration files`);
}

// ────────────────────────────────────────────────────────────────
// Helpers
// ────────────────────────────────────────────────────────────────

function findBinary(name: string): string | null {
  try {
    const result = execSync(
      process.platform === 'win32' ? `where ${name}` : `which ${name}`,
      { encoding: 'utf8' }
    ).trim();
    return result.split('\n')[0].trim() || null;
  } catch {
    return null;
  }
}

function stopManagedPostgres(): void {
  const rorcaHome = join(homedir(), '.rorca');
  const pgCtl = join(rorcaHome, 'postgres', 'bin', process.platform === 'win32' ? 'pg_ctl.exe' : 'pg_ctl');
  const dataDir = join(rorcaHome, 'data');

  if (!existsSync(pgCtl) || !existsSync(dataDir)) return;

  try {
    execSync(`"${pgCtl}" stop -D "${dataDir}" -m fast -w`, {
      encoding: 'utf-8',
      timeout: 15_000,
      stdio: 'pipe',
    });
    console.log('PostgreSQL stopped.');
  } catch {
    // best-effort
  }
}

function openBrowser(url: string): void {
  try {
    if (process.platform === 'darwin') {
      execSync(`open "${url}"`);
    } else if (process.platform === 'win32') {
      execSync(`start "" "${url}"`);
    } else {
      execSync(`xdg-open "${url}"`);
    }
  } catch {
    console.log(`Open ${url} in your browser.`);
  }
}
