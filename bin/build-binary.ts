/**
 * DIST-004: Build script for creating a standalone Rorca binary via `bun build --compile`.
 *
 * Steps:
 *   1. Build frontend (vite build → dist/)
 *   2. Generate embedded asset manifest (imports all dist/ files + migration .sql files)
 *   3. Run `bun build --compile` with a plugin that remaps better-sqlite3 → bun:sqlite shim
 *
 * Usage:
 *   bun run bin/build-binary.ts
 */

import { execSync } from 'child_process';
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync, readFileSync } from 'fs';
import { join, relative } from 'path';

const ROOT = join(import.meta.dir, '..');
const DIST_DIR = join(ROOT, 'dist');
const MIGRATIONS_DIR = join(ROOT, 'backend', 'src', 'db', 'migrations');
const GENERATED_DIR = join(ROOT, 'bin', '.generated');
const OUT_FILE = join(ROOT, 'rorca');
const BUN_SHIM = join(ROOT, 'backend', 'src', 'db', 'bun-sqlite-shim.ts');

// ── Step 0: Ensure generated directory exists ──
if (!existsSync(GENERATED_DIR)) {
  mkdirSync(GENERATED_DIR, { recursive: true });
}

// ── Step 1: Build frontend ──
console.log('Step 1/4: Building frontend...');
if (!existsSync(join(DIST_DIR, 'index.html'))) {
  execSync('npx vite build', { cwd: ROOT, stdio: 'inherit' });
}
if (!existsSync(join(DIST_DIR, 'index.html'))) {
  console.error('Frontend build failed — dist/index.html not found');
  process.exit(1);
}
console.log('  Frontend built.\n');

// ── Step 2: Collect all files to embed ──
console.log('Step 2/4: Collecting embedded assets...');

function walkDir(dir: string, base: string = dir): string[] {
  const results: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      results.push(...walkDir(full, base));
    } else {
      results.push(relative(base, full));
    }
  }
  return results;
}

const distFiles = walkDir(DIST_DIR);
console.log(`  ${distFiles.length} frontend files`);

const migrationFiles = readdirSync(MIGRATIONS_DIR)
  .filter(f => f.endsWith('.sql'))
  .sort();
console.log(`  ${migrationFiles.length} migration files`);

// ── Step 3: Generate embedded asset module ──
console.log('\nStep 3/4: Generating embedded assets module...');

// Inline migrations as strings (small SQL text files)
const migrationEntries: string[] = [];
for (const file of migrationFiles) {
  const content = readFileSync(join(MIGRATIONS_DIR, file), 'utf-8');
  migrationEntries.push(`  ['${file}', ${JSON.stringify(content)}]`);
}

// Frontend assets use bun's `with { type: "file" }` import for binary embedding
const assetImports: string[] = [];
const assetEntries: string[] = [];
for (let i = 0; i < distFiles.length; i++) {
  const relPath = distFiles[i];
  const varName = `asset_${i}`;
  const importPath = relative(GENERATED_DIR, join(DIST_DIR, relPath)).replace(/\\/g, '/');
  assetImports.push(`import ${varName} from '${importPath}' with { type: 'file' };`);
  assetEntries.push(`  ['${relPath}', ${varName}]`);
}

const embeddedModule = `/**
 * Auto-generated by bin/build-binary.ts — DO NOT EDIT
 * Contains embedded frontend assets and SQL migrations for the compiled binary.
 */

${assetImports.join('\n')}

/** Map of relative path → embedded file path (resolved by bun at runtime) */
export const embeddedAssets: Map<string, string> = new Map([
${assetEntries.join(',\n')}
]);

/** Map of migration filename → SQL content (inlined at build time) */
export const embeddedMigrations: Map<string, string> = new Map([
${migrationEntries.join(',\n')}
]);
`;

writeFileSync(join(GENERATED_DIR, 'embedded-assets.ts'), embeddedModule);
console.log('  Generated embedded-assets.ts');

// ── Step 4: Compile with Bun.build API ──
console.log('\nStep 4/4: Compiling binary...');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf-8'));
const version = pkg.version;

// Plugin: remap 'better-sqlite3' → bun:sqlite shim
const betterSqlitePlugin: import('bun').BunPlugin = {
  name: 'better-sqlite3-to-bun-sqlite',
  setup(build) {
    build.onResolve({ filter: /^better-sqlite3$/ }, () => {
      return { path: BUN_SHIM };
    });
  },
};

const result = await Bun.build({
  entrypoints: [join(ROOT, 'bin', 'rorca-bun.ts')],
  outdir: ROOT,
  compile: true,
  target: 'bun',
  minify: true,
  define: {
    'RORCA_VERSION': JSON.stringify(version),
  },
  naming: {
    asset: '[name].[ext]',
  },
  plugins: [betterSqlitePlugin],
  external: [
    // Node builtins / optional native deps that shouldn't be bundled
    'fsevents',
  ],
});

if (!result.success) {
  console.error('Compilation failed:');
  for (const log of result.logs) {
    console.error(`  ${log}`);
  }
  process.exit(1);
}

// Find the compiled binary from outputs (bun uses entry filename as output name)
const compiledPath = result.outputs.length > 0 ? result.outputs[0].path : '';
console.log(`  Bun output: ${compiledPath}`);

// Rename to 'rorca' if needed
if (compiledPath && compiledPath !== OUT_FILE) {
  const { renameSync } = await import('fs');
  if (existsSync(OUT_FILE)) {
    const { unlinkSync } = await import('fs');
    unlinkSync(OUT_FILE);
  }
  renameSync(compiledPath, OUT_FILE);
}

if (existsSync(OUT_FILE)) {
  // Make executable
  const { chmodSync } = await import('fs');
  chmodSync(OUT_FILE, 0o755);

  const binarySize = statSync(OUT_FILE).size;
  const sizeMB = (binarySize / 1024 / 1024).toFixed(1);
  console.log(`\nBinary built: ${OUT_FILE}`);
  console.log(`Size: ${sizeMB} MB`);

  if (binarySize > 100 * 1024 * 1024) {
    console.warn(`WARNING: Binary size (${sizeMB} MB) exceeds 100 MB target`);
  }

  console.log('\nTest with:');
  console.log(`  ./rorca --version`);
  console.log(`  ./rorca start --no-open`);
} else {
  console.error('Binary not found at expected path — check bun build output above.');
  process.exit(1);
}
