/**
 * One-command local database bootstrap.
 *
 *   node scripts/db-up.mjs              # start the bundled Postgres and wait for it
 *   node scripts/db-up.mjs --migrate    # start it, then run migrations to completion
 *   node scripts/db-up.mjs --down       # stop the stack
 *
 * Credentials are generated with crypto.randomBytes on first use and written to
 * `.env.local` (mode 0600, gitignored). Nothing is committed and there are no
 * default passwords: a fresh clone gets fresh secrets.
 */

import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_FILE = path.join(ROOT, '.env.local');
const COMPOSE = process.env.RORCA_COMPOSE_BIN?.trim() || 'docker';
const READY_TIMEOUT_MS = Number(process.env.RORCA_DB_READY_TIMEOUT_MS || 180_000) || 180_000;

/** Secret material the compose stack refuses to start without. */
const REQUIRED_SECRETS = [
  'RORCA_POSTGRES_BOOTSTRAP_USER',
  'RORCA_POSTGRES_BOOTSTRAP_PASSWORD',
  'RORCA_MIGRATION_DATABASE_USER',
  'RORCA_MIGRATION_DATABASE_PASSWORD',
  'RORCA_RUNTIME_DATABASE_USER',
  'RORCA_RUNTIME_DATABASE_PASSWORD',
  'RORCA_CANONICAL_WRITER_DATABASE_USER',
  'RORCA_CANONICAL_WRITER_DATABASE_PASSWORD',
];

const DERIVED_URLS = {
  RORCA_MIGRATION_DATABASE_URL: 'RORCA_MIGRATION_DATABASE_USER',
  RORCA_RUNTIME_DATABASE_URL: 'RORCA_RUNTIME_DATABASE_USER',
  RORCA_CANONICAL_WRITER_DATABASE_URL: 'RORCA_CANONICAL_WRITER_DATABASE_USER',
};

const USERS = {
  RORCA_POSTGRES_BOOTSTRAP_USER: 'rorca_bootstrap',
  RORCA_MIGRATION_DATABASE_USER: 'rorca_migrator',
  RORCA_RUNTIME_DATABASE_USER: 'rorca_runtime',
  RORCA_CANONICAL_WRITER_DATABASE_USER: 'rorca_canonical_writer',
};

function secret() {
  return randomBytes(24).toString('base64url');
}

function parseEnv(text) {
  const out = new Map();
  for (const line of text.split('\n')) {
    const m = /^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (m) out.set(m[1], m[2].trim());
  }
  return out;
}

/** Create .env.local with generated credentials when the required keys are absent. */
function ensureEnvFile() {
  let values = new Map();
  if (existsSync(ENV_FILE)) values = parseEnv(readFileSync(ENV_FILE, 'utf8'));

  const added = [];
  for (const key of REQUIRED_SECRETS) {
    if (values.get(key)) continue;
    values.set(key, USERS[key] ?? secret());
    added.push(key);
  }
  if (!values.get('RORCA_POSTGRES_DATABASE')) values.set('RORCA_POSTGRES_DATABASE', 'rorca');

  // docker compose interpolates the entire file before selecting a service, so
  // every required variable must resolve even when only `db` is started.
  const database = values.get('RORCA_POSTGRES_DATABASE');
  for (const [urlKey, userKey] of Object.entries(DERIVED_URLS)) {
    if (values.get(urlKey)) continue;
    const user = values.get(userKey);
    const pass = values.get(userKey.replace(/_USER$/, '_PASSWORD'));
    values.set(urlKey, `postgresql://${user}:${encodeURIComponent(pass)}@db:5432/${database}`);
    added.push(urlKey);
  }

  if (added.length) {
    const generated = new Set(REQUIRED_SECRETS.filter(k => /_PASSWORD$/.test(k)));
    for (const key of generated) {
      if (!added.includes(key)) continue;
      values.set(key, secret());
    }
    const lines = [
      '# Generated by scripts/db-up.mjs — never commit this file.',
      '# Used by docker compose for the local development stack.',
      '# Regenerate with: rm .env.local && npm run db:up',
      ...[...values.entries()].map(([k, v]) => `${k}=${v}`),
    ];
    writeFileSync(ENV_FILE, lines.join('\n') + '\n', { mode: 0o600 });
    try { chmodSync(ENV_FILE, 0o600); } catch { /* best effort on exotic filesystems */ }
    console.log(`  created ${path.relative(ROOT, ENV_FILE)} with generated credentials (0600)`);
  }
  return values;
}

function run(args, { capture = false } = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(COMPOSE, args, {
      cwd: ROOT,
      stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
      env: { ...process.env, COMPOSE_ENV_FILES: ENV_FILE },
    });
    let out = '';
    if (capture) {
      child.stdout.on('data', d => { out += String(d); });
      child.stderr.on('data', d => { out += String(d); });
    }
    child.on('error', reject);
    child.on('close', code => (code === 0 ? resolve(out) : reject(new Error(`${COMPOSE} ${args.join(' ')} exited ${code}${out ? `\n${out.trim()}` : ''}`))));
  });
}

async function waitForDb(bootstrapUser) {
  const deadline = Date.now() + READY_TIMEOUT_MS;
  process.stdout.write('  waiting for PostgreSQL');
  while (Date.now() < deadline) {
    try {
      await run(['compose', 'exec', '-T', 'db', 'pg_isready', '-U', bootstrapUser, '-d', 'rorca'], { capture: true });
      process.stdout.write(' — ready\n');
      return;
    } catch {
      process.stdout.write('.');
      await new Promise(r => setTimeout(r, 2000));
    }
  }
  throw new Error(`PostgreSQL did not become ready within ${Math.round(READY_TIMEOUT_MS / 1000)}s. Check: npm run db:logs`);
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const values = ensureEnvFile();

  if (args.has('--down')) {
    console.log('Stopping the local stack…');
    await run(['compose', 'down']);
    return;
  }

  console.log('Starting the bundled PostgreSQL (Apache AGE + pgvector)…');
  await run(['compose', 'up', '-d', 'db']);
  await waitForDb(values.get('RORCA_POSTGRES_BOOTSTRAP_USER'));

  if (args.has('--migrate')) {
    console.log('Applying migrations to completion…');
    await run(['compose', 'up', '--abort-on-container-exit', 'db-migrate']);
    console.log('  migrations applied');
  }

  console.log('\nNext:');
  console.log('  npm run dev        # dashboard + backend on http://localhost:5210 / :3030');
  console.log('  npm run db:logs    # follow database logs');
  console.log('  npm run db:down    # stop the stack');
}

main().catch((err) => {
  console.error(`\n✗ ${err instanceof Error ? err.message : String(err)}`);
  process.exit(1);
});
