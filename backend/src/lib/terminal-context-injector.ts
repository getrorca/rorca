import fs from 'fs/promises';
import path from 'path';
import { queryOne } from '../db/index';
import { synthesize } from './direction-stack';

const RORCA_MARKER_START = '# === RORCA DIRECTION START ===';
const RORCA_MARKER_END = '# === RORCA DIRECTION END ===';

type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };
type JsonObject = { [key: string]: JsonValue };

function stripRorcaSection(content: string): string {
  const startIdx = content.indexOf(RORCA_MARKER_START);
  const endIdx = content.indexOf(RORCA_MARKER_END);

  if (startIdx === -1 || endIdx === -1) {
    return content;
  }

  const before = content.substring(0, startIdx);
  const after = content.substring(endIdx + RORCA_MARKER_END.length);
  return before.replace(/\n+$/, '\n') + after.replace(/^\n+/, '');
}

function buildRorcaSection(directionText: string): string {
  return [
    '',
    RORCA_MARKER_START,
    '',
    '# Rorca Direction Stack',
    '',
    'This section is auto-generated by Rorca before each terminal session.',
    'It contains the synthesized direction stack context for this workspace.',
    'Do NOT edit manually — it will be overwritten on the next session.',
    '',
    directionText,
    '',
    RORCA_MARKER_END,
    '',
  ].join('\n');
}

function isPlainObject(value: JsonValue): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function removeModelKey(value: JsonValue): JsonValue {
  if (!isPlainObject(value)) {
    return value;
  }

  const rest: JsonObject = { ...value };
  delete rest.model;
  return rest;
}

function isEmptyObject(value: JsonValue): boolean {
  return isPlainObject(value) && Object.keys(value).length === 0;
}

export async function injectDirectionStack(
  workspaceId: string,
  workspacePath: string,
  model: string,
): Promise<{ cleanup: () => Promise<void> }> {
  const l1Row = await queryOne<{ content_yaml: string }>(
    `SELECT content_yaml FROM direction_layers WHERE layer = 1 AND COALESCE(workspace_id, '') = '' AND COALESCE(domain, '') = ''`
  );

  const wsRow = await queryOne<{ domain: string | null }>('SELECT domain FROM workspaces WHERE id = $1', [workspaceId]);
  const domain = wsRow?.domain;

  const l2Row = domain
    ? await queryOne<{ content_yaml: string }>(
      `SELECT content_yaml FROM direction_layers WHERE layer = 2 AND domain = $1 AND COALESCE(workspace_id, '') = ''`,
      [domain]
    )
    : undefined;

  const l3Row = await queryOne<{ content_yaml: string }>(
    `SELECT content_yaml FROM direction_layers WHERE layer = 3 AND workspace_id = $1 AND COALESCE(domain, '') = ''`,
    [workspaceId]
  );

  const ctx = await queryOne<{ schema_snapshot: string | null }>(
    `SELECT schema_snapshot FROM workspace_context WHERE workspace_id = $1`,
    [workspaceId]
  );

  const access = await queryOne<{ team_id: string }>(
    'SELECT team_id FROM workspace_access WHERE workspace_id = $1 LIMIT 1',
    [workspaceId]
  );

  let teamL1: string | undefined;
  let teamL2: string | undefined;
  if (access) {
    const tl1 = await queryOne<{ content_yaml: string }>(
      `SELECT content_yaml FROM direction_layers WHERE layer = 1 AND team_id = $1 AND COALESCE(workspace_id,'') = '' AND COALESCE(domain,'') = ''`,
      [access.team_id]
    );
    const tl2 = await queryOne<{ content_yaml: string }>(
      `SELECT content_yaml FROM direction_layers WHERE layer = 2 AND team_id = $1 AND COALESCE(workspace_id,'') = '' AND COALESCE(domain,'') = ''`,
      [access.team_id]
    );
    teamL1 = tl1?.content_yaml;
    teamL2 = tl2?.content_yaml;
  }

  const directionText = synthesize({
    l1: l1Row?.content_yaml,
    l2: l2Row?.content_yaml,
    l3: l3Row?.content_yaml,
    teamL1,
    teamL2,
    schemaSnapshot: ctx?.schema_snapshot || undefined,
    specBrief: 'OpenCode terminal session context. No active spec or story is attached to this session.',
  });

  const opencodeDir = path.join(workspacePath, '.opencode');
  const agentsPath = path.join(opencodeDir, 'AGENTS.md');
  const configPath = path.join(opencodeDir, 'config.json');

  await fs.mkdir(opencodeDir, { recursive: true });

  let agentsExisted = false;
  let agentsOriginalContent: string | null = null;
  try {
    agentsOriginalContent = await fs.readFile(agentsPath, 'utf8');
    agentsExisted = true;
  } catch {
    agentsOriginalContent = null;
  }

  const rorcaSection = buildRorcaSection(directionText);
  if (agentsExisted && agentsOriginalContent !== null) {
    const cleaned = stripRorcaSection(agentsOriginalContent);
    await fs.writeFile(agentsPath, cleaned + rorcaSection, 'utf8');
  } else {
    await fs.writeFile(agentsPath, rorcaSection.trimStart(), 'utf8');
  }

  let configExisted = false;
  let configCreatedByRorca = false;
  let parsedConfig: JsonValue = {};
  try {
    const configContent = await fs.readFile(configPath, 'utf8');
    configExisted = true;
    parsedConfig = JSON.parse(configContent) as JsonValue;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
      configCreatedByRorca = true;
      parsedConfig = {};
    } else {
      parsedConfig = {};
    }
  }

  const nextConfig = isPlainObject(parsedConfig) ? { ...parsedConfig, model } : { model };
  await fs.writeFile(configPath, `${JSON.stringify(nextConfig, null, 2)}\n`, 'utf8');

  let cleanedUp = false;

  return {
    cleanup: async () => {
      if (cleanedUp) {
        return;
      }
      cleanedUp = true;

      try {
        if (!agentsExisted) {
          await fs.unlink(agentsPath).catch(() => undefined);
        } else if (agentsOriginalContent !== null) {
          await fs.writeFile(agentsPath, agentsOriginalContent, 'utf8');
        } else {
          const current = await fs.readFile(agentsPath, 'utf8').catch(() => null);
          if (current !== null) {
            const stripped = stripRorcaSection(current);
            await fs.writeFile(agentsPath, stripped, 'utf8');
          }
        }
      } catch {
      }

      try {
        const currentConfigContent = await fs.readFile(configPath, 'utf8').catch(() => null);
        if (currentConfigContent !== null) {
          let currentConfig: JsonValue = {};
          try {
            currentConfig = JSON.parse(currentConfigContent) as JsonValue;
          } catch {
            currentConfig = {};
          }

          const withoutModel = removeModelKey(currentConfig);
          if ((configCreatedByRorca || !configExisted) && isEmptyObject(withoutModel)) {
            await fs.unlink(configPath).catch(() => undefined);
          } else {
            await fs.writeFile(configPath, `${JSON.stringify(withoutModel, null, 2)}\n`, 'utf8');
          }
        }
      } catch {
      }
    },
  };
}
