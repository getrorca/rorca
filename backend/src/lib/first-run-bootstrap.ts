/**
 * first-run-bootstrap.ts — make `rorca start` work from a bare machine.
 *
 * The standalone binary ships no database. Before the Express server can load
 * it needs a PostgreSQL cluster with the production split-principal topology,
 * the canonical migrations applied, and the pg-boss transport schema installed.
 * This module performs that whole sequence idempotently:
 *
 *   1. resolve PostgreSQL binaries (downloaded cache, else a local install)
 *   2. initdb / start / createdb on the managed port
 *   3. provision rorca_migrator, rorca_runtime, rorca_canonical_writer
 *   4. generate credentials + service tokens into ~/.rorca/.env (0600)
 *   5. apply migrations and install the pg-boss transport schema
 *
 * Nothing here runs when the operator already supplied DATABASE_URL — a BYOP or
 * compose-managed database stays authoritative.
 */

import { execFileSync } from 'child_process';
import { createHash, randomBytes } from 'crypto';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { PostgresManager } from './postgres-manager';
import { logger } from './logger';

const RORCA_HOME = path.join(os.homedir(), '.rorca');
const ENV_FILE = path.join(RORCA_HOME, '.env');
const SCHEMA_MARKER = path.join(RORCA_HOME, '.schema-version');
const DATABASE = 'rorca';
const DEFAULT_PORT = 5433;

/** Secrets the server refuses to start without. */
const GENERATED_TOKENS = [
  'RORCA_INTERNAL_SERVICE_TOKEN',
  'RORCA_DISPATCH_RECEIVER_TOKEN',
  'RORCA_RETRY_APPROVAL_SECRET',
];

const ROLE_KEYS = {
  bootstrap: ['RORCA_POSTGRES_BOOTSTRAP_USER', 'RORCA_POSTGRES_BOOTSTRAP_PASSWORD'],
  migration: ['RORCA_MIGRATION_DATABASE_USER', 'RORCA_MIGRATION_DATABASE_PASSWORD'],
  runtime: ['RORCA_RUNTIME_DATABASE_USER', 'RORCA_RUNTIME_DATABASE_PASSWORD'],
  writer: ['RORCA_CANONICAL_WRITER_DATABASE_USER', 'RORCA_CANONICAL_WRITER_DATABASE_PASSWORD'],
} as const;

/** Role names are fixed: migrations and pg-boss reference the topology by name. */
const ROLE_NAMES = {
  bootstrap: 'rorca_bootstrap',
  migration: 'rorca_migrator',
  runtime: 'rorca_runtime',
  writer: 'rorca_canonical_writer',
} as const;

export interface FirstRunResult {
  databaseUrl: string;
  port: number;
  provisioned: boolean;
}

/** True when the operator (or compose) already supplied a database. */
export function isDatabaseConfigured(env: NodeJS.ProcessEnv = process.env): boolean {
  return Boolean(env.DATABASE_URL?.trim() || env.RORCA_RUNTIME_DATABASE_URL?.trim());
}

function secret(): string {
  return randomBytes(24).toString('base64url');
}

function token(): string {
  return randomBytes(48).toString('base64url');
}

/** SQL string literal — single quotes are the only escape surface. */
function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function ident(name: string): string {
  if (!/^[A-Za-z0-9_]+$/.test(name)) throw new Error(`invalid database role name: ${name}`);
  return `"${name}"`;
}

function roleUrl(user: string, password: string, port: number): string {
  return `postgresql://${encodeURIComponent(user)}:${encodeURIComponent(password)}@127.0.0.1:${port}/${DATABASE}`;
}

function readEnvFile(): Map<string, string> {
  const values = new Map<string, string>();
  try {
    for (const line of fs.readFileSync(ENV_FILE, 'utf-8').split('\n')) {
      const match = /^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/.exec(line);
      if (match) values.set(match[1], match[2].trim());
    }
  } catch {
    // No previous run.
  }
  return values;
}

function writeEnvFile(values: Map<string, string>): void {
  fs.mkdirSync(RORCA_HOME, { recursive: true });
  const body = [
    '# Generated by `rorca start` on first run — never commit this file.',
    '# Local split-principal credentials for the Rorca-managed database.',
    ...[...values.entries()].map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n');
  fs.writeFileSync(ENV_FILE, body, { mode: 0o600 });
  try {
    fs.chmodSync(ENV_FILE, 0o600);
  } catch {
    // best effort on exotic filesystems
  }
}

/**
 * Load previously generated credentials, generating any that are missing.
 * Passwords are never rotated on restart: the URL, the role definition, and the
 * stored env must keep agreeing or the next connection fails authentication.
 */
function ensureCredentials(port: number): Map<string, string> {
  const values = readEnvFile();
  let changed = false;

  for (const [role, [userKey, passwordKey]] of Object.entries(ROLE_KEYS)) {
    if (!values.get(userKey)) {
      values.set(userKey, ROLE_NAMES[role as keyof typeof ROLE_NAMES]);
      changed = true;
    }
    if (!values.get(passwordKey)) {
      values.set(passwordKey, secret());
      changed = true;
    }
  }

  for (const key of GENERATED_TOKENS) {
    if (!values.get(key)) {
      values.set(key, token());
      changed = true;
    }
  }

  const urls: Record<string, string> = {
    RORCA_MIGRATION_DATABASE_URL: roleUrl(
      values.get(ROLE_KEYS.migration[0])!,
      values.get(ROLE_KEYS.migration[1])!,
      port
    ),
    RORCA_RUNTIME_DATABASE_URL: roleUrl(
      values.get(ROLE_KEYS.runtime[0])!,
      values.get(ROLE_KEYS.runtime[1])!,
      port
    ),
    RORCA_CANONICAL_WRITER_DATABASE_URL: roleUrl(
      values.get(ROLE_KEYS.writer[0])!,
      values.get(ROLE_KEYS.writer[1])!,
      port
    ),
  };
  for (const [key, value] of Object.entries(urls)) {
    if (values.get(key) !== value) {
      values.set(key, value);
      changed = true;
    }
  }

  if (changed || !fs.existsSync(ENV_FILE)) writeEnvFile(values);
  return values;
}

/**
 * Split-principal provisioning. Mirrors docker/postgres/bootstrap-roles.sh so a
 * binary install and a compose install end up with the same authority topology:
 * the migration owner is a non-superuser, extensions are created by the offline
 * bootstrap administrator (the only principal that can), and no application
 * role is a member of another.
 */
function provisioningSql(values: Map<string, string>): string {
  const migration = values.get(ROLE_KEYS.migration[0])!;
  const runtime = values.get(ROLE_KEYS.runtime[0])!;
  const writer = values.get(ROLE_KEYS.writer[0])!;
  const appRoles = [migration, runtime, writer];

  const statements: string[] = [
    '-- Split-principal topology (mirrors docker/postgres/bootstrap-roles.sh)',
  ];

  for (const role of appRoles) {
    const password = values.get(
      Object.values(ROLE_KEYS).find(([userKey]) => values.get(userKey) === role)![1]
    )!;
    statements.push(
      `DO $$ BEGIN
         IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ${lit(role)}) THEN
           CREATE ROLE ${ident(role)} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD ${lit(password)};
         END IF;
       END $$;`,
      `ALTER ROLE ${ident(role)} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD ${lit(password)};`
    );
  }

  // PostgREST-style compatibility roles referenced by RLS policies.
  for (const role of ['authenticated', 'anon']) {
    statements.push(
      `DO $$ BEGIN
         IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ${lit(role)}) THEN
           CREATE ROLE ${ident(role)} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
         END IF;
       END $$;`,
      `ALTER ROLE ${ident(role)} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;`
    );
  }

  // Any cross-membership would collapse the authority split.
  statements.push(`DO $$
    DECLARE membership RECORD;
    BEGIN
      FOR membership IN
        SELECT granted.rolname AS granted_role, member.rolname AS member_role
        FROM pg_auth_members memberships
        JOIN pg_roles granted ON granted.oid = memberships.roleid
        JOIN pg_roles member ON member.oid = memberships.member
        WHERE granted.rolname IN (${[...appRoles, 'authenticated', 'anon'].map(lit).join(', ')})
          AND member.rolname IN (${[...appRoles, 'authenticated', 'anon'].map(lit).join(', ')})
      LOOP
        EXECUTE format('REVOKE %I FROM %I', membership.granted_role, membership.member_role);
      END LOOP;
    END $$;`);

  // Extensions must exist before migrations run: the migration owner is
  // deliberately not a superuser and cannot create them itself.
  for (const extension of ['vector', 'pgcrypto', 'age']) {
    statements.push(`DO $$
      BEGIN
        IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = ${lit(extension)}) THEN
          CREATE EXTENSION IF NOT EXISTS ${ident(extension)};
          EXECUTE format('GRANT USAGE ON SCHEMA %I TO %I', (
            SELECT n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace WHERE e.extname = ${lit(extension)}
          ), ${lit(migration)});
        END IF;
      EXCEPTION WHEN insufficient_privilege THEN
        RAISE NOTICE 'skipping extension %: insufficient privilege', ${lit(extension)};
      END $$;`);
  }

  // AGE exposes its graph catalog through ag_catalog; both app roles read it.
  statements.push(`DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'age') THEN
        EXECUTE format('GRANT USAGE ON SCHEMA ag_catalog TO %I, %I', ${lit(migration)}, ${lit(runtime)});
        GRANT SELECT ON ag_catalog.ag_graph, ag_catalog.ag_label TO ${ident(runtime)};
      END IF;
    END $$;`);

  statements.push(
    `ALTER DATABASE ${ident(DATABASE)} OWNER TO ${ident(migration)};`,
    `REVOKE CREATE ON SCHEMA public FROM PUBLIC;`,
    `GRANT CONNECT ON DATABASE ${ident(DATABASE)} TO ${ident(migration)}, ${ident(runtime)}, ${ident(writer)};`,
    `GRANT USAGE ON SCHEMA public TO ${ident(migration)}, ${ident(runtime)}, ${ident(writer)};`
  );

  return statements.join('\n');
}

function runPsql(mgr: PostgresManager, sql: string, label: string): void {
  const sqlFile = path.join(RORCA_HOME, `.bootstrap-${Date.now()}.sql`);
  fs.writeFileSync(sqlFile, sql, { mode: 0o600 });
  try {
    execFileSync(
      mgr.getPsqlPath(),
      [
        '--no-psqlrc',
        '--set',
        'ON_ERROR_STOP=1',
        '--host',
        '127.0.0.1',
        '--port',
        String(mgr.port),
        '--username',
        process.env.USER || os.userInfo().username,
        '--dbname',
        DATABASE,
        '--file',
        sqlFile,
      ],
      { encoding: 'utf-8', timeout: 120_000, stdio: 'pipe', env: { ...process.env, LC_ALL: 'C' } }
    );
  } catch (err) {
    const stderr = (err as { stderr?: string }).stderr ?? '';
    throw new Error(`${label} failed: ${stderr.trim() || (err as Error).message}`);
  } finally {
    try {
      fs.unlinkSync(sqlFile);
    } catch {
      // best effort
    }
  }
}

/** Fingerprint of the migration set, so restarts skip a no-op migration pass. */
function schemaFingerprint(migrationsDir: string): string {
  const files = fs
    .readdirSync(migrationsDir)
    .filter((file) => file.endsWith('.sql'))
    .sort();
  return createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 32);
}

function currentSchemaMarker(): string | null {
  try {
    return fs.readFileSync(SCHEMA_MARKER, 'utf-8').trim() || null;
  } catch {
    return null;
  }
}

function writeSchemaMarker(value: string): void {
  fs.writeFileSync(SCHEMA_MARKER, `${value}\n`, { mode: 0o600 });
}

function exportEnv(values: Map<string, string>): void {
  for (const [key, value] of values) {
    process.env[key] = value;
  }
}

/**
 * Provision the local database and leave process.env pointing at it.
 * Safe to call on every start: cluster creation, roles, migrations and the
 * pg-boss schema are all idempotent.
 */
export async function bootstrapFirstRun(opts?: {
  port?: number;
  migrationsDir?: string;
}): Promise<FirstRunResult | null> {
  if (isDatabaseConfigured()) {
    logger.info('[first-run] DATABASE_URL supplied by the operator — skipping local provisioning');
    return null;
  }

  const port = opts?.port ?? DEFAULT_PORT;
  fs.mkdirSync(RORCA_HOME, { recursive: true });

  const mgr = new PostgresManager({ port });
  logger.info('[first-run] resolving PostgreSQL binaries…');
  await mgr.ensureInstalled();
  mgr.initCluster();
  await mgr.start();
  mgr.createDatabase();

  const pgvector = mgr.verifyPgvector();
  if (!pgvector.ok) throw new Error(pgvector.fixPath ?? 'pgvector is required but unavailable');

  const values = ensureCredentials(port);
  logger.info('[first-run] provisioning split-principal roles…');
  runPsql(mgr, provisioningSql(values), 'role provisioning');

  exportEnv(values);

  const migrationUrl = values.get('RORCA_MIGRATION_DATABASE_URL')!;
  const runtimeUrl = values.get('RORCA_RUNTIME_DATABASE_URL')!;
  process.env.DATABASE_URL = migrationUrl;
  process.env.RORCA_RUNTIME_DATABASE_USER = values.get(ROLE_KEYS.runtime[0])!;
  process.env.RORCA_CANONICAL_WRITER_DATABASE_USER = values.get(ROLE_KEYS.writer[0])!;

  const migrationsDir = opts?.migrationsDir ?? process.env.RORCA_MIGRATIONS_DIR;
  let fingerprint: string | null = null;
  if (migrationsDir && fs.existsSync(migrationsDir)) {
    fingerprint = schemaFingerprint(migrationsDir);
  }

  const needsMigration = fingerprint === null || currentSchemaMarker() !== fingerprint;

  if (needsMigration) {
    logger.info('[first-run] applying canonical migrations…');
    const { runPgMigrations } = await import('../db/pg-index');
    await runPgMigrations();

    logger.info('[first-run] installing pg-boss transport schema…');
    const { prepareSplitPrincipalPgBoss } = await import('./pg-boss');
    const { getPgBossSchemaName } = await import('./pg-boss-schema');
    await prepareSplitPrincipalPgBoss(migrationUrl, getPgBossSchemaName());

    if (fingerprint) writeSchemaMarker(fingerprint);
  } else {
    logger.info('[first-run] schema up to date — skipping migrations');
  }

  // The API and worker run as the least-privileged principal.
  process.env.DATABASE_URL = runtimeUrl;
  process.env.RORCA_DB_MODE = 'native';

  logger.info(`[first-run] ready — database ${runtimeUrl.replace(/:[^:@/]+@/, ':***@')}`);
  return { databaseUrl: runtimeUrl, port, provisioned: true };
}
