import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import type { Express } from 'express';
import request from 'supertest';
import { getAuthToken } from './helpers/auth-helper';
import { execute, query, queryOne, closePool } from '../../db/index';

jest.mock('../../lib/llm-client', () => ({
  chatComplete: jest.fn(),
  getActiveProvider: jest.fn().mockReturnValue('claude-cli'),
  isValidModel: jest.fn().mockReturnValue(true),
  DEFAULT_MODEL: 'claude-sonnet-4-5-20250929',
  resolveVaultProvider: jest.fn().mockReturnValue(null),
  getModelInfo: jest.fn().mockReturnValue(undefined),
  SUPPORTED_MODELS: ['claude-sonnet-4-5-20250929'],
}));

let app: Express;
let tmpDir: string;
let authToken: string;
const workspaceId = `ws-memcons-test-${Date.now()}`;

beforeAll(async () => {
  process.env.NODE_ENV = 'test';
  const serverMod = require('../../server');
  app = serverMod.default;
  authToken = await getAuthToken(app);

  tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'rorca-memcons-test-'));

  await execute(
    `INSERT INTO workspaces (id, label, path) VALUES ($1, $2, $3) ON CONFLICT (id) DO NOTHING`,
    [workspaceId, 'Memory Consolidation Test', tmpDir],
  );
});

afterAll(async () => {
  // Clean up all test data by workspaceId
  await execute(`DELETE FROM memories WHERE workspace_id = $1`, [workspaceId]);
  await execute(`DELETE FROM workspaces WHERE id = $1`, [workspaceId]);

  fs.rmSync(tmpDir, { recursive: true, force: true });
  delete process.env.NODE_ENV;
  await closePool();
});

// ─── generateMemoryMd ─────────────────────────────────────────────────────

describe('generateMemoryMd', () => {
  test('returns content containing inserted memory in correct format', async () => {
    // Insert a test memory row directly
    const row = await queryOne<{ id: string }>(
      `INSERT INTO memories (workspace_id, category, content, confidence, related_files, source_type)
       VALUES ($1, $2, $3, $4, $5, $6) RETURNING id`,
      [workspaceId, 'Architecture', 'Use connection pooling: Always use pg Pool with max 20 connections', 'high', '[]', 'manual'],
    );
    expect(row).toBeDefined();


    const { generateMemoryMd } = require('../../lib/memory-projection');
    const output: string = await generateMemoryMd(workspaceId);

    // Verify header
    expect(output).toMatch(
      /^<!-- Auto-generated by Rorca — do not edit\. Changes will be overwritten before the next story\. -->/,
    );
    expect(output).toContain('# Memory Ledger (recent decisions)');

    // Verify entry format: ## YYYY-MM-DD [Category] first line of content
    expect(output).toMatch(/## \d{4}-\d{2}-\d{2} \[Architecture\] Use connection pooling/);
    expect(output).toContain('> Rule: Use connection pooling: Always use pg Pool with max 20 connections');
  });
});

// ─── writeMemoryMd ────────────────────────────────────────────────────────

describe('writeMemoryMd', () => {
  test('writes MEMORY.md to disk starting with the read-only header', async () => {
    const { writeMemoryMd } = require('../../lib/memory-projection');
    await writeMemoryMd(workspaceId, tmpDir);

    const memoryPath = path.join(tmpDir, 'MEMORY.md');
    expect(fs.existsSync(memoryPath)).toBe(true);

    const content = fs.readFileSync(memoryPath, 'utf-8');
    expect(content).toMatch(
      /^<!-- Auto-generated by Rorca — do not edit\. Changes will be overwritten before the next story\. -->/,
    );
    expect(content).toContain('[Architecture] Use connection pooling');
  });
});

// ─── proposed_memories.json flow ──────────────────────────────────────────

describe('proposed_memories.json flow', () => {
  test('POST /api/memory inserts entries from proposed_memories, verifies DB rows and cleanup', async () => {
    const rorcaDir = path.join(tmpDir, '.rorca');
    fs.mkdirSync(rorcaDir, { recursive: true });

    const proposed = [
      {
        category: 'Convention',
        title: 'Always use strict TypeScript',
        rule: 'Enable strict mode in all tsconfig.json files.',
        context: 'Prevents runtime type errors.',
        source: 'US-007',
      },
      {
        category: 'Bug Fix',
        title: 'Fix off-by-one in pagination',
        rule: 'Pagination offset must be (page - 1) * pageSize, not page * pageSize.',
        context: '',
        source: 'US-007',
      },
    ];

    // Write proposed_memories.json
    const proposedPath = path.join(rorcaDir, 'proposed_memories.json');
    fs.writeFileSync(proposedPath, JSON.stringify(proposed), 'utf-8');
    expect(fs.existsSync(proposedPath)).toBe(true);

    // Simulate the execution-engine flow: POST each entry to /api/memory
    for (const entry of proposed) {
      const res = await request(app)
        .post('/api/memory')
        .set('Authorization', `Bearer ${authToken}`)
        .send({ workspaceId, ...entry });

      expect(res.status).toBe(201);
      expect(res.body.entry).toBeDefined();
      expect(res.body.entry.category).toBe(entry.category);
      expect(res.body.entry.title).toBe(entry.title);
    }

    // Verify rows in DB
    const dbRows = await query<{ id: string; category: string; content: string }>(
      `SELECT id, category, content FROM memories
       WHERE workspace_id = $1 AND deleted_at IS NULL AND content LIKE '%Always use strict TypeScript%'`,
      [workspaceId],
    );
    expect(dbRows.length).toBeGreaterThanOrEqual(1);


    const dbRows2 = await query<{ id: string; category: string; content: string }>(
      `SELECT id, category, content FROM memories
       WHERE workspace_id = $1 AND deleted_at IS NULL AND content LIKE '%off-by-one%'`,
      [workspaceId],
    );
    expect(dbRows2.length).toBeGreaterThanOrEqual(1);

    // Simulate cleanup (execution-engine deletes the file after processing)
    fs.unlinkSync(proposedPath);
    expect(fs.existsSync(proposedPath)).toBe(false);
  });

  test('generateMemoryMd includes newly added memories from proposed flow', async () => {
    const { generateMemoryMd } = require('../../lib/memory-projection');
    const output: string = await generateMemoryMd(workspaceId);

    // Original memory from first test
    expect(output).toContain('Use connection pooling');
    // Newly added from proposed flow
    expect(output).toContain('Always use strict TypeScript');
    expect(output).toContain('Fix off-by-one in pagination');
  });
});
